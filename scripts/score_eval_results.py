import argparse
import json
from pathlib import Path
from typing import Any


def load_jsonl(path: Path) -> list[dict[str, Any]]:
    rows: list[dict[str, Any]] = []
    for line in path.read_text(encoding="utf-8").splitlines():
        if line.strip():
            rows.append(json.loads(line))
    return rows


def split_expected_values(value: Any) -> list[str]:
    if value is None:
        return []
    text = str(value)
    return [part.strip() for part in text.split("_or_") if part.strip()]


def score_row(row: dict[str, Any]) -> dict[str, Any]:
    checks: dict[str, bool] = {}

    reply = str(row.get("reply", ""))
    observed_source = str(row.get("observed_source", ""))

    expected_sources = split_expected_values(row.get("expected_source"))
    if expected_sources:
        checks["source_match"] = observed_source in expected_sources

    expected_contains = row.get("expected_contains")
    if expected_contains is not None:
        checks["contains_match"] = str(expected_contains).lower() in reply.lower()

    expected_decline = row.get("expected_decline")
    if isinstance(expected_decline, bool):
        reply_has_decline_phrase = "cannot answer" in reply.lower()
        checks["decline_match"] = (reply_has_decline_phrase == expected_decline)

    if row.get("expected_source") == "redis-semantic-cache":
        checks["cache_hit_match"] = bool(row.get("observed_cache_hit", False))

    passed = all(checks.values()) if checks else False

    return {
        **row,
        "checks": checks,
        "passed": passed,
    }


def summarize(scored_rows: list[dict[str, Any]]) -> dict[str, Any]:
    total = len(scored_rows)
    passed = sum(1 for row in scored_rows if row.get("passed"))
    failed = total - passed

    failed_examples = [
        {
            "input": row.get("input"),
            "observed_source": row.get("observed_source"),
            "expected_source": row.get("expected_source"),
            "checks": row.get("checks"),
        }
        for row in scored_rows
        if not row.get("passed")
    ]

    return {
        "total": total,
        "passed": passed,
        "failed": failed,
        "pass_rate": round((passed / total) * 100, 2) if total else 0.0,
        "all_passed": failed == 0 and total > 0,
        "failed_examples": failed_examples,
    }


def write_jsonl(path: Path, rows: list[dict[str, Any]]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(json.dumps(row, ensure_ascii=False) for row in rows) + "\n", encoding="utf-8")


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="Score replayed eval rows and return pass/fail status.")
    parser.add_argument(
        "--input",
        default="datasets/evals/observed-results.jsonl",
        help="Observed results JSONL generated by replay script.",
    )
    parser.add_argument(
        "--output",
        default="datasets/evals/scored-results.jsonl",
        help="Scored per-row JSONL output.",
    )
    parser.add_argument(
        "--summary",
        default="datasets/evals/score-summary.json",
        help="Summary JSON output.",
    )
    return parser.parse_args()


def main() -> int:
    args = parse_args()
    input_path = Path(args.input)
    rows = load_jsonl(input_path)
    if not rows:
        print(f"No rows found in {input_path}")
        return 1

    scored_rows = [score_row(row) for row in rows]
    summary = summarize(scored_rows)

    write_jsonl(Path(args.output), scored_rows)
    Path(args.summary).write_text(json.dumps(summary, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")

    print(f"Scored {summary['total']} rows")
    print(f"Passed: {summary['passed']}")
    print(f"Failed: {summary['failed']}")
    print(f"Pass rate: {summary['pass_rate']}%")

    if summary["all_passed"]:
        print("Regression check: PASS")
        return 0

    print("Regression check: FAIL")
    return 1


if __name__ == "__main__":
    raise SystemExit(main())
